def words_in(text: str) -> list[str]:
    return re.findall(r"[A-Za-z0-9][A-Za-z0-9'-]*", text)


def render_plain_transcript(metadata: dict) -> str:
    """Render the meeting in the plain-text format used by data/meeting-transcript.txt."""
    section_order = list(dict.fromkeys(turn[3] for turn in TURNS))
    section_words = {
        section: sum(len(words_in(text)) for _, text, _, s in TURNS if s == section)
        for section in section_order
    }

    words_per_minute = 140
    section_starts: dict[str, float] = {}
    elapsed = 0.0
    for section in section_order:
        section_starts[section] = elapsed
        elapsed += section_words[section] / words_per_minute * 60

    base = datetime(2026, 11, 12, 10, 0)

    def clock(seconds: float) -> str:
        # Round up so section markers stay monotonic at minute precision.
        moment = base + timedelta(minutes=math.ceil(seconds / 60))
        return moment.strftime("%I:%M %p").lstrip("0")

    first_names = {p["id"]: p["full_name"].split()[0] for p in PARTICIPANTS}

    lines = [
        "MEETING TRANSCRIPT",
        f"Project: {metadata['project']['name']} ({metadata['project']['company']}) - Release {metadata['project']['release']} readiness review",
        "Date: November 12, 2026",
        f"Time: {clock(0)} - {clock(elapsed)}",
        f"Location: {metadata['location']}",
        "Recording: Synthetic teaching fixture. All names, organizations, and details are fictional. No real meeting was recorded.",
        "",
        "Participants:",
    ]
    for participant in PARTICIPANTS:
        lines.append(
            f"- {participant['full_name']} ({participant['role']}) - "
            f"\"{first_names[participant['id']]}\""
        )

    lines += ["", "Agenda distributed in advance:"]
    for i, item in enumerate(metadata["agenda"], 1):
        lines.append(f"{i}. {item}")

    lines += ["", "---", ""]
    current_section = None
    for speaker_id, text, _, section in TURNS:
        if section != current_section:
            current_section = section
            if lines[-1] != "":
                lines.append("")
            lines += [f"[{clock(section_starts[section])} - {section}]", ""]
        lines += [f"{first_names[speaker_id]}: {text}", ""]

    lines += [
        f"[{clock(elapsed)} - Recording stopped]",
        f"[Meeting adjourned at {clock(elapsed)}]",
        "",
        "---",
        "",
        f"{GENERATED_MARKER}. Do not edit by hand; rerun the script instead.",
        "",
    ]
    return "\n".join(lines)


