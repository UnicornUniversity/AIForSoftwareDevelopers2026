def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    word_count = sum(len(words_in(text)) for _, text, _, _ in TURNS)
    # 120–160 words per minute is a normal conversational range.
    est_min_lo = round(word_count / 160, 1)
    est_min_hi = round(word_count / 120, 1)

    metadata = {
        "schema_version": "1.0",
        "fixture_id": FIXTURE_ID,
        "meeting_id": MEETING_ID,
        "title": TITLE,
        "language": LANGUAGE,
        "fictional": True,
        "disclaimer": "All names, organization names, technical details, dates, and numbers in this script are fictional and were created solely for the teaching demo.",
        "created": "2026-11-12",
        "meeting_date": "2026-11-12",
        "planned_release": "2026-11-19",
        "location": "Conference Room B, Brightline Components HQ / Hybrid",
        "plain_text_transcript": "data/meeting-transcript.txt",
        "duration_target_seconds": [180, 300],
        "estimated_duration_seconds": [int(est_min_lo * 60), int(est_min_hi * 60)],
        "duration_estimate_basis": (
            f"{word_count} spoken words at 160-120 words per minute"
        ),
        "turn_count": len(TURNS),
        "word_count_estimate": word_count,
        "project": {
            "name": "Atlas Procurement Portal",
            "company": "Brightline Components Ltd.",
            "release": "2.4",
            "topic": "SDLC release-readiness review: implementation, API integration, database migration, testing, risks, and deployment",
        },
        "participants": PARTICIPANTS,
        "agenda": [
            "Implementation status and external integration",
            "Database migration",
            "Regression testing and risks",
            "Deployment window and on-call coverage",
            "Release scope decision",
        ],
        "technical_terms_covered": {
            term: [
                i
                for i, (_, text, _, _) in enumerate(TURNS, 1)
                if term.lower() in text.lower()
            ]
            for term in TERMS
        },
        "recording_notes": [
            "No overlapping speech in the primary fixture.",
            "Participant names never appear inside spoken utterances.",
            "Speaker labels are explicit on every turn.",
            "Delivery notes describe tone only and do not change the words.",
            "Do not generate audio until the TTS step (prompt 02).",
        ],
    }

    script = {
        "schema_version": "1.0",
        "fixture_id": FIXTURE_ID,
        "meeting_id": MEETING_ID,
        "title": TITLE,
        "language": LANGUAGE,
        "fictional": True,
        "participant_ids": PARTICIPANT_IDS,
        "turns": [
            {
                "index": i,
                "speaker_id": speaker_id,
                "text": text,
                "delivery": delivery,
                "section": section,
            }
            for i, (speaker_id, text, delivery, section) in enumerate(TURNS, 1)
        ],
    }

    ground_truth = {
        "schema_version": "1.0",
        "fixture_id": FIXTURE_ID,
        "meeting_id": MEETING_ID,
        "language": LANGUAGE,
        "derived_from": "meeting_script.json",
        "participant_ids": PARTICIPANT_IDS,
        "turn_count": len(TURNS),
        "turns": [
            {"index": i, "speaker_id": speaker_id, "text": text}
            for i, (speaker_id, text, _, _) in enumerate(TURNS, 1)
        ],
        "notes": [
            "Exact spoken text and speaker IDs; the reference for WER and speaker-attribution evaluation.",
            "Do not pass this file, the participant names, or the turn map to either ASR system during a blind run.",
        ],
    }

    def dump(path: Path, obj: object) -> None:
        path.write_text(
            json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )

    dump(OUT / "meeting_metadata.json", metadata)
    dump(OUT / "meeting_script.json", script)
    dump(OUT / "ground_truth.json", ground_truth)

    names = {p["id"]: p["full_name"] for p in PARTICIPANTS}
    lines = [
        f"# {TITLE}",
        "",
        "> **Fictional teaching fixture.** All names, organizations, technical details, and numbers are fictional.",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Meeting ID | `{MEETING_ID}` |",
        f"| Language | {LANGUAGE} |",
        f"| Project | {metadata['project']['name']} ({metadata['project']['company']}), release {metadata['project']['release']} |",
        "| Target duration | 3–5 minutes |",
        f"| Turns | {len(TURNS)} |",
        "",
        "## Participants",
        "",
        "| ID | Name | Role | Voice |",
        "| --- | --- | --- | --- |",
    ]
    for p in PARTICIPANTS:
        lines.append(f"| `{p['id']}` | {p['full_name']} | {p['role']} | {p['gender']} |")

    lines += ["", "## Script", ""]
    current_section = None
    for i, (speaker_id, text, delivery, section) in enumerate(TURNS, 1):
        if section != current_section:
            current_section = section
            lines += [f"### {section}", ""]
        lines += [
            f"**{i}. {speaker_id} — {names[speaker_id]}** *({delivery})*",
            "",
            f"> {text}",
            "",
        ]

    lines += [
        "---",
        "",
        "This file is the readable view of `meeting_script.json`. The JSON files are the source of truth if anything differs.",
        "",
    ]
    (OUT / "meeting_script_readable.md").write_text("\n".join(lines), encoding="utf-8")

    plain = render_plain_transcript(metadata)
    if PLAIN_PATH.exists():
        existing = PLAIN_PATH.read_text(encoding="utf-8")
        if GENERATED_MARKER not in existing:
            raise SystemExit(
                f"Refusing to overwrite {PLAIN_PATH}: it does not look generated. "
                "Archive it first, then rerun."
            )
    PLAIN_PATH.write_text(plain, encoding="utf-8")

    metadata_markdown = render_metadata_markdown(metadata)
    if METADATA_PATH.exists():
        existing = METADATA_PATH.read_text(encoding="utf-8")
        if existing.strip() and GENERATED_MARKER not in existing:
            raise SystemExit(
                f"Refusing to overwrite {METADATA_PATH}: it does not look generated. "
                "Archive it first, then rerun."
            )
    METADATA_PATH.write_text(metadata_markdown, encoding="utf-8")

    # ---- Validation -------------------------------------------------------
    loaded_script = json.loads((OUT / "meeting_script.json").read_text(encoding="utf-8"))
    loaded_gt = json.loads((OUT / "ground_truth.json").read_text(encoding="utf-8"))
    loaded_meta = json.loads((OUT / "meeting_metadata.json").read_text(encoding="utf-8"))

    assert len(TURNS) >= 30, "prompt 01 requires at least 30 speaker turns"
    assert {t[0] for t in TURNS} == set(PARTICIPANT_IDS)
    assert [t["text"] for t in loaded_script["turns"]] == [
        t["text"] for t in loaded_gt["turns"]
    ]
    assert [t["speaker_id"] for t in loaded_script["turns"]] == [
        t["speaker_id"] for t in loaded_gt["turns"]
    ]

    joined = " ".join(text for _, text, _, _ in TURNS).lower()
    for term in TERMS:
        assert term.lower() in joined, f"missing required term: {term}"
    for term, turn_numbers in loaded_meta["technical_terms_covered"].items():
        assert turn_numbers, f"metadata reports no turns for {term}"

    name_forms = {"ann", "bob", "greg", "smith", "hawkins", "cox"}
    for name in name_forms:
        assert not re.search(rf"\b{name}\b", joined), (
            f"participant name appears in spoken text: {name}"
        )

    for marker in ("[", "]", "(laughter)", "(pause)", "overlapping"):
        assert marker not in joined, f"unexpected stage/overlap marker: {marker}"

    first_names = {p["id"]: p["full_name"].split()[0] for p in PARTICIPANTS}
    plain_text = PLAIN_PATH.read_text(encoding="utf-8")
    assert GENERATED_MARKER in plain_text
    for speaker_id, text, _, _ in TURNS:
        expected = f"{first_names[speaker_id]}: {text}"
        assert expected in plain_text, f"plain transcript missing turn: {expected[:60]}"

    metadata_text = METADATA_PATH.read_text(encoding="utf-8")
    assert GENERATED_MARKER in metadata_text
    assert "Do not pass this file" in metadata_text
    for participant in PARTICIPANTS:
        assert f"`{participant['id']}`" in metadata_text
        assert participant["full_name"] in metadata_text
        assert participant["gender"] in metadata_text
        assert participant["voice_requirements"]["character"] in metadata_text

    counts = Counter(t[0] for t in TURNS)
    print(f"Wrote {OUT}")
    print(f"Wrote {PLAIN_PATH}")
    print(f"Wrote {METADATA_PATH}")
    print(f"turns={len(TURNS)} words={word_count} "
          f"estimated_minutes={est_min_lo}-{est_min_hi}")
    print(f"speakers={dict(counts)}")
    print(f"sections={list(dict.fromkeys(t[3] for t in TURNS))}")
    print("validation: OK")


if __name__ == "__main__":
    main()
