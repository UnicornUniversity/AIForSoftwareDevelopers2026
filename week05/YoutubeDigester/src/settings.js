function int(value, fallback, { min = -Infinity, max = Infinity } = {}, name, warn) {
  if (typeof value !== 'number' || !Number.isInteger(value)) {
    if (value !== undefined) warn(`[settings] ${name}=${JSON.stringify(value)} is not an integer; using ${fallback}`);
    return fallback;
  }
  if (value < min || value > max) {
    warn(`[settings] ${name}=${value} is outside [${min}, ${max}]; using ${fallback}`);
    return fallback;
  }
  return value;
}

function num(value, fallback, { min = -Infinity, max = Infinity } = {}, name, warn) {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    if (value !== undefined) warn(`[settings] ${name}=${JSON.stringify(value)} is not a number; using ${fallback}`);
    return fallback;
  }
  if (value < min || value > max) {
    warn(`[settings] ${name}=${value} is outside [${min}, ${max}]; using ${fallback}`);
    return fallback;
  }
  return value;
}

function str(value, fallback, name, warn, { max = 500 } = {}) {
  if (typeof value !== 'string' || value.trim() === '') {
    if (value !== undefined) warn(`[settings] ${name} must be a non-empty string; using the default`);
    return fallback;
  }
  return value.trim().slice(0, max);
}

/** API keys may legitimately be blank; blank falls back to the environment. */
function optionalStr(value, fallback, name, warn) {
  if (value === undefined || value === null) return fallback;
  if (typeof value !== 'string') {
    warn(`[settings] ${name} must be a string; using the environment value`);
    return fallback;
  }
  const trimmed = value.trim();
  return trimmed === '' ? fallback : trimmed;
}

function bool(value, fallback, name, warn) {
  if (typeof value !== 'boolean') {
    if (value !== undefined) warn(`[settings] ${name} must be true or false; using ${fallback}`);
    return fallback;
  }
  return value;
}

function oneOf(value, allowed, fallback, name, warn) {
  if (typeof value !== 'string' || !allowed.includes(value)) {
    if (value !== undefined) warn(`[settings] ${name} must be one of ${allowed.join(', ')}; using ${fallback}`);
    return fallback;
  }
  return value;
}

function colour(value, fallback, name, warn) {
  if (typeof value !== 'string' || !COLOUR_PATTERN.test(value)) {
    if (value !== undefined) warn(`[settings] ${name} must be a #rrggbb colour; using ${fallback}`);
    return fallback;
  }
  return value;
}

function languageList(value, fallback, name, warn) {
  if (!Array.isArray(value)) {
    if (value !== undefined) warn(`[settings] ${name} must be an array of language tags; using ${fallback.join(', ')}`);
    return [...fallback];
  }

  const cleaned = value
    .filter((tag) => typeof tag === 'string')
    .map((tag) => tag.trim().toLowerCase())
    .filter((tag) => LANGUAGE_PATTERN.test(tag));

  if (cleaned.length === 0) {
    warn(`[settings] ${name} has no usable language tags; using ${fallback.join(', ')}`);
    return [...fallback];
  }
  return [...new Set(cleaned)].slice(0, MAX_LANGUAGES);
}

/** A relative path that stays inside the app folder. */
function relativePath(value, fallback, name, warn) {
  const candidate = str(value, fallback, name, warn);
  const normalised = path.normalize(candidate);
  if (path.isAbsolute(normalised) || normalised.split(path.sep).includes('..')) {
    warn(`[settings] ${name} must be a relative path inside the app; using ${fallback}`);
    return fallback;
  }
  return candidate;
}

function plainFilename(value, fallback, name, warn) {
  const candidate = str(value, fallback, name, warn);
  if (candidate.includes('/') || candidate.includes('\\') || candidate === '.' || candidate === '..') {
    warn(`[settings] ${name} must be a plain file name; using ${fallback}`);
    return fallback;
  }
  return candidate;
}

function margin(value, fallback, side, warn) {
  const source = value && typeof value === 'object' ? value : {};
  return int(source[side], fallback[side], { min: 5, max: 50 }, `pdf.style.marginMm.${side}`, warn);
}

/**
 * Validate a parsed settings object. Unknown keys are dropped; every malformed
 * value falls back with a warning instead of failing the run. API keys resolve
 * from the file first, then the environment.
 */
export function validateSettings(input, { warn = console.warn, env = process.env } = {}) {
  const source = input && typeof input === 'object' && !Array.isArray(input) ? input : {};
  const youtube = source.youtube && typeof source.youtube === 'object' ? source.youtube : {};
  const deepseek = source.deepseek && typeof source.deepseek === 'object' ? source.deepseek : {};
  const transcript = source.transcript && typeof source.transcript === 'object' ? source.transcript : {};
  const llm = source.llm && typeof source.llm === 'object' ? source.llm : {};
  const pdf = source.pdf && typeof source.pdf === 'object' ? source.pdf : {};
  const style = pdf.style && typeof pdf.style === 'object' ? pdf.style : {};
  const colors = style.colors && typeof style.colors === 'object' ? style.colors : {};
  const margins = style.marginMm && typeof style.marginMm === 'object' ? style.marginMm : {};
  const output = source.output && typeof source.output === 'object' ? source.output : {};
  const jobs = source.jobs && typeof source.jobs === 'object' ? source.jobs : {};

  const topicsMin = int(llm.topicsMin, DEFAULT_SETTINGS.llm.topicsMin, { min: 3, max: 15 }, 'llm.topicsMin', warn);
  let topicsMax = int(llm.topicsMax, DEFAULT_SETTINGS.llm.topicsMax, { min: 3, max: 20 }, 'llm.topicsMax', warn);
  if (topicsMax < topicsMin) {
    warn(`[settings] llm.topicsMax (${topicsMax}) is below llm.topicsMin (${topicsMin}); using both defaults`);
    topicsMax = DEFAULT_SETTINGS.llm.topicsMax;
  }

  const chapterMaxInputChars = int(
    llm.chapterMaxInputChars,
    DEFAULT_SETTINGS.llm.chapterMaxInputChars,
    { min: 1000, max: 50_000 },
    'llm.chapterMaxInputChars',
    warn,
  );
  let chapterMaxTotalInputChars = int(
    llm.chapterMaxTotalInputChars,
    DEFAULT_SETTINGS.llm.chapterMaxTotalInputChars,
    { min: 1000, max: 200_000 },
    'llm.chapterMaxTotalInputChars',
    warn,
  );
  if (chapterMaxTotalInputChars < chapterMaxInputChars) {
    warn('[settings] llm.chapterMaxTotalInputChars is below llm.chapterMaxInputChars; using the default total');
    chapterMaxTotalInputChars = DEFAULT_SETTINGS.llm.chapterMaxTotalInputChars;
  }

  const pdfName = plainFilename(output.pdfName, DEFAULT_SETTINGS.output.pdfName, 'output.pdfName', warn);

  return {
    youtube: {
      apiKey: optionalStr(youtube.apiKey, env.YOUTUBE_API_KEY ?? '', 'youtube.apiKey', warn),
      maxVideos: int(youtube.maxVideos, DEFAULT_SETTINGS.youtube.maxVideos, { min: 1, max: 200 }, 'youtube.maxVideos', warn),
      timeoutMs: int(youtube.timeoutMs, DEFAULT_SETTINGS.youtube.timeoutMs, { min: 1000, max: 120_000 }, 'youtube.timeoutMs', warn),
      retries: int(youtube.retries, DEFAULT_SETTINGS.youtube.retries, { min: 0, max: 3 }, 'youtube.retries', warn),
      includeShorts: bool(youtube.includeShorts, DEFAULT_SETTINGS.youtube.includeShorts, 'youtube.includeShorts', warn),
      minDurationSeconds: int(youtube.minDurationSeconds, DEFAULT_SETTINGS.youtube.minDurationSeconds, { min: 0, max: 3600 }, 'youtube.minDurationSeconds', warn),
      minTitleMatch: num(youtube.minTitleMatch, DEFAULT_SETTINGS.youtube.minTitleMatch, { min: 0, max: 1 }, 'youtube.minTitleMatch', warn),
      searchMaxResults: int(youtube.searchMaxResults, DEFAULT_SETTINGS.youtube.searchMaxResults, { min: 1, max: 50 }, 'youtube.searchMaxResults', warn),
      searchPages: int(youtube.searchPages, DEFAULT_SETTINGS.youtube.searchPages, { min: 1, max: 3 }, 'youtube.searchPages', warn),
      playlistSearchMaxResults: int(youtube.playlistSearchMaxResults, DEFAULT_SETTINGS.youtube.playlistSearchMaxResults, { min: 1, max: 20 }, 'youtube.playlistSearchMaxResults', warn),
    },
    deepseek: {
      apiKey: optionalStr(deepseek.apiKey, env.DEEPSEEK_API_KEY ?? '', 'deepseek.apiKey', warn),
      baseURL: str(deepseek.baseURL, env.DEEPSEEK_BASE_URL || DEFAULT_SETTINGS.deepseek.baseURL, 'deepseek.baseURL', warn),
      model: str(deepseek.model, env.DEEPSEEK_MODEL || DEFAULT_SETTINGS.deepseek.model, 'deepseek.model', warn),
      timeoutMs: int(deepseek.timeoutMs, DEFAULT_SETTINGS.deepseek.timeoutMs, { min: 1000, max: 180_000 }, 'deepseek.timeoutMs', warn),
      maxTokens: int(deepseek.maxTokens, DEFAULT_SETTINGS.deepseek.maxTokens, { min: 256, max: 32_000 }, 'deepseek.maxTokens', warn),
      temperature: num(deepseek.temperature, DEFAULT_SETTINGS.deepseek.temperature, { min: 0, max: 1 }, 'deepseek.temperature', warn),
    },
    transcript: {
      languages: languageList(transcript.languages, DEFAULT_SETTINGS.transcript.languages, 'transcript.languages', warn),
      allowAutoGenerated: bool(transcript.allowAutoGenerated, DEFAULT_SETTINGS.transcript.allowAutoGenerated, 'transcript.allowAutoGenerated', warn),
      concurrency: int(transcript.concurrency, DEFAULT_SETTINGS.transcript.concurrency, { min: 1, max: 8 }, 'transcript.concurrency', warn),
      requestDelayMs: int(transcript.requestDelayMs, DEFAULT_SETTINGS.transcript.requestDelayMs, { min: 0, max: 5000 }, 'transcript.requestDelayMs', warn),
      rateLimitRetries: int(transcript.rateLimitRetries, DEFAULT_SETTINGS.transcript.rateLimitRetries, { min: 0, max: 2 }, 'transcript.rateLimitRetries', warn),
      timeoutMs: int(transcript.timeoutMs, DEFAULT_SETTINGS.transcript.timeoutMs, { min: 1000, max: 120_000 }, 'transcript.timeoutMs', warn),
      maxChars: int(transcript.maxChars, DEFAULT_SETTINGS.transcript.maxChars, { min: 10_000, max: 1_000_000 }, 'transcript.maxChars', warn),
    },
    llm: {
      topicsMin,
      topicsMax,
      clusterMaxCharsPerVideo: int(llm.clusterMaxCharsPerVideo, DEFAULT_SETTINGS.llm.clusterMaxCharsPerVideo, { min: 200, max: 5000 }, 'llm.clusterMaxCharsPerVideo', warn),
      clusterMaxTotalChars: int(llm.clusterMaxTotalChars, DEFAULT_SETTINGS.llm.clusterMaxTotalChars, { min: 5000, max: 200_000 }, 'llm.clusterMaxTotalChars', warn),
      chapterMaxInputChars,
      chapterMaxTotalInputChars,
      chapterConcurrency: int(llm.chapterConcurrency, DEFAULT_SETTINGS.llm.chapterConcurrency, { min: 1, max: 4 }, 'llm.chapterConcurrency', warn),
      chapterMaxSections: int(llm.chapterMaxSections, DEFAULT_SETTINGS.llm.chapterMaxSections, { min: 1, max: 20 }, 'llm.chapterMaxSections', warn),
      chapterMaxChars: int(llm.chapterMaxChars, DEFAULT_SETTINGS.llm.chapterMaxChars, { min: 1000, max: 30_000 }, 'llm.chapterMaxChars', warn),
    },
    pdf: {
      title: str(pdf.title, DEFAULT_SETTINGS.pdf.title, 'pdf.title', warn, { max: 200 }),
      subtitle: typeof pdf.subtitle === 'string' ? pdf.subtitle.trim().slice(0, 300) : DEFAULT_SETTINGS.pdf.subtitle,
      includeCover: bool(pdf.includeCover, DEFAULT_SETTINGS.pdf.includeCover, 'pdf.includeCover', warn),
      includeToc: bool(pdf.includeToc, DEFAULT_SETTINGS.pdf.includeToc, 'pdf.includeToc', warn),
      pageNumbers: bool(pdf.pageNumbers, DEFAULT_SETTINGS.pdf.pageNumbers, 'pdf.pageNumbers', warn),
      pageSize: oneOf(pdf.pageSize, PAGE_SIZES, DEFAULT_SETTINGS.pdf.pageSize, 'pdf.pageSize', warn),
      style: {
        name: str(style.name, DEFAULT_SETTINGS.pdf.style.name, 'pdf.style.name', warn, { max: 200 }),
        tonePrompt: str(style.tonePrompt, DEFAULT_SETTINGS.pdf.style.tonePrompt, 'pdf.style.tonePrompt', warn, { max: 4000 }),
        readingLevel: str(style.readingLevel, DEFAULT_SETTINGS.pdf.style.readingLevel, 'pdf.style.readingLevel', warn, { max: 100 }),
        fontFamily: str(style.fontFamily, DEFAULT_SETTINGS.pdf.style.fontFamily, 'pdf.style.fontFamily', warn, { max: 300 }),
        headingFontFamily: str(style.headingFontFamily, DEFAULT_SETTINGS.pdf.style.headingFontFamily, 'pdf.style.headingFontFamily', warn, { max: 300 }),
        bodyFontSizePt: num(style.bodyFontSizePt, DEFAULT_SETTINGS.pdf.style.bodyFontSizePt, { min: 8, max: 24 }, 'pdf.style.bodyFontSizePt', warn),
        lineHeight: num(style.lineHeight, DEFAULT_SETTINGS.pdf.style.lineHeight, { min: 1, max: 2.5 }, 'pdf.style.lineHeight', warn),
        marginMm: {
          top: margin(margins, DEFAULT_SETTINGS.pdf.style.marginMm, 'top', warn),
          right: margin(margins, DEFAULT_SETTINGS.pdf.style.marginMm, 'right', warn),
          bottom: margin(margins, DEFAULT_SETTINGS.pdf.style.marginMm, 'bottom', warn),
          left: margin(margins, DEFAULT_SETTINGS.pdf.style.marginMm, 'left', warn),
        },
        colors: {
          ink: colour(colors.ink, DEFAULT_SETTINGS.pdf.style.colors.ink, 'pdf.style.colors.ink', warn),
          muted: colour(colors.muted, DEFAULT_SETTINGS.pdf.style.colors.muted, 'pdf.style.colors.muted', warn),
          paper: colour(colors.paper, DEFAULT_SETTINGS.pdf.style.colors.paper, 'pdf.style.colors.paper', warn),
          accent: colour(colors.accent, DEFAULT_SETTINGS.pdf.style.colors.accent, 'pdf.style.colors.accent', warn),
          rule: colour(colors.rule, DEFAULT_SETTINGS.pdf.style.colors.rule, 'pdf.style.colors.rule', warn),
        },
        coverBackground: colour(style.coverBackground, DEFAULT_SETTINGS.pdf.style.coverBackground, 'pdf.style.coverBackground', warn),
        showVideoCitations: bool(style.showVideoCitations, DEFAULT_SETTINGS.pdf.style.showVideoCitations, 'pdf.style.showVideoCitations', warn),
      },
    },
    output: {
      dir: relativePath(output.dir, DEFAULT_SETTINGS.output.dir, 'output.dir', warn),
      pdfName,
    },
    jobs: {
      concurrency: int(jobs.concurrency, DEFAULT_SETTINGS.jobs.concurrency, { min: 1, max: 4 }, 'jobs.concurrency', warn),
      stateWriteIntervalMs: int(jobs.stateWriteIntervalMs, DEFAULT_SETTINGS.jobs.stateWriteIntervalMs, { min: 250, max: 5000 }, 'jobs.stateWriteIntervalMs', warn),
      maxWarnings: int(jobs.maxWarnings, DEFAULT_SETTINGS.jobs.maxWarnings, { min: 1, max: 200 }, 'jobs.maxWarnings', warn),
    },
  };
}

/** Settings safe to show in the UI: keys become booleans, never values. */
export function redactSettings(settings) {
  return {
    ...settings,
    youtube: { ...settings.youtube, apiKey: '', hasApiKey: settings.youtube.apiKey !== '' },
    deepseek: { ...settings.deepseek, apiKey: '', hasApiKey: settings.deepseek.apiKey !== '' },
  };
}

/**
 * Read settings.json. A missing file is normal and yields the defaults; a
 * malformed file warns and yields the defaults rather than losing the app.
 */
export async function loadSettings(filePath = SETTINGS_PATH, { warn = console.warn, env = process.env } = {}) {
  let text;
  try {
    text = await readFile(filePath, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') {
      warn(`[settings] ${filePath} not found; using built-in defaults`);
      return validateSettings({}, { warn, env });
    }
    throw err;
  }

  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch (err) {
    warn(`[settings] ${filePath} is not valid JSON (${err.message}); using built-in defaults`);
    return validateSettings({}, { warn, env });
  }

  return validateSettings(parsed, { warn, env });
}
