import { discoverCourse } from './discover.js';
import { clusterTopics as defaultClusterTopics } from './llm.js';
import { createTranscriptFetcher } from './transcript.js';
import { createYouTubeClient } from './youtube.js';

export class IngestError extends Error {
  constructor(code, message) {
    super(message);
    this.name = 'IngestError';
    this.code = code;
    this.expose = true;
  }
}

function throwIfAborted(signal) {
  if (signal?.aborted) throw new IngestError('cancelled', 'The ingest was cancelled.');
}

function addAll(target, values) {
  for (const value of values ?? []) {
    if (typeof value === 'string' && value.trim() !== '' && !target.includes(value)) target.push(value);
  }
}

/**
 * Discovery → metadata → transcripts → topics. Every stage records progress on
 * the job and a user-safe course status, and partial results survive a failure.
 */
export async function runIngest({
  courseId,
  jobId = null,
  depot,
  settings = {},
  youtube = null,
  transcripts = null,
  llm = null,
  force = false,
  signal,
  update = () => {},
  addWarning = () => {},
  now = () => new Date(),
} = {}) {
  const course = await depot.getCourse(courseId);
  if (!course) throw new IngestError('course_not_found', 'That course does not exist.');

  const youtubeSettings = settings.youtube ?? {};
  const transcriptSettings = settings.transcript ?? {};
  const llmSettings = settings.llm ?? {};
  const deepseek = settings.deepseek ?? {};
  const warnings = [];

  const note = (message) => {
    if (typeof message !== 'string' || message.trim() === '') return;
    addAll(warnings, [message]);
    addWarning(message);
  };

  const youtubeClient = youtube ?? createYouTubeClient({
    apiKey: youtubeSettings.apiKey ?? '',
    timeoutMs: youtubeSettings.timeoutMs,
    retries: youtubeSettings.retries,
  });

  const transcriptFetcher = transcripts ?? createTranscriptFetcher({
    languages: transcriptSettings.languages,
    allowAutoGenerated: transcriptSettings.allowAutoGenerated,
    timeoutMs: transcriptSettings.timeoutMs,
    maxChars: transcriptSettings.maxChars,
    rateLimitRetries: transcriptSettings.rateLimitRetries,
    concurrency: transcriptSettings.concurrency,
    warn: note,
  });

  const cluster = llm?.clusterTopics ?? defaultClusterTopics;

  try {
    // 1. Discovery.
    update({ stage: 'discovering', progress: { total: 0, done: 0, failed: 0 } });
    await depot.updateCourse(courseId, { status: 'discovering', stage: 'discovering', error: null });
    throwIfAborted(signal);

    const discovery = await discoverCourse({
      seed: course.seed,
      client: youtubeClient,
      settings,
      signal,
      warn: note,
    });
    addAll(warnings, discovery.warnings);

    if (!discovery.videos || discovery.videos.length === 0) {
      throw new IngestError(
        'discovery_failed',
        'No videos were found for this course. Check the link and the YouTube API key, then try again.',
      );
    }

    await depot.updateCourse(courseId, {
      title: discovery.courseTitle || course.title,
      channelId: discovery.channelId ?? course.channelId,
      channelTitle: discovery.channelTitle ?? course.channelTitle,
      playlistId: discovery.playlistId ?? course.playlistId,
      discovery: discovery.discovery,
    });
    if (discovery.channelId) {
      await depot.upsertChannel({ id: discovery.channelId, title: discovery.channelTitle });
    }

    // 2. Metadata, best effort. Playlist items already carry titles.
    update({ stage: 'metadata', progress: { total: discovery.videos.length, done: 0, failed: 0 } });
    throwIfAborted(signal);

    const discovered = [];
    for (const video of discovery.videos) {
      if (video?.videoId && !discovered.some((entry) => entry.videoId === video.videoId)) {
        discovered.push(video);
      }
    }

    let enriched = discovered;
    if (youtubeClient.hasKey?.() !== false && typeof youtubeClient.getVideos === 'function') {
      try {
        const metas = await youtubeClient.getVideos(discovered.map((video) => video.videoId), { signal });
        const byId = new Map(metas.map((meta) => [meta.videoId, meta]));
        enriched = discovered.map((video) => ({ ...video, ...(byId.get(video.videoId) ?? {}) }));
      } catch (err) {
        if (signal?.aborted) throw err;
        note('Video details could not be loaded; using the titles from the course listing.');
      }
    }

    const orderedIds = [];
    for (const [index, video] of enriched.entries()) {
      await depot.upsertVideo(courseId, {
        videoId: video.videoId,
        title: video.title || video.videoId,
        channel: video.channel || discovery.channelTitle || '',
        channelId: video.channelId || discovery.channelId || null,
        publishedAt: video.publishedAt ?? null,
        durationSeconds: video.durationSeconds ?? 0,
        position: index,
        url: `https://www.youtube.com/watch?v=${video.videoId}`,
      });
      orderedIds.push(video.videoId);
    }
    await depot.setCourseVideos(courseId, orderedIds);

    // 3. Transcripts.
    await depot.updateCourse(courseId, { status: 'transcribing', stage: 'transcribing' });
    throwIfAborted(signal);
    const before = await depot.listVideos(courseId);
    const targets = before.filter((video) => force || video.status !== 'ok');
    let done = before.length - targets.length;
    let failed = 0;
    const total = before.length;
    update({ stage: 'transcribing', progress: { total, done, failed } });

    if (targets.length > 0) {
      const byId = new Map(before.map((video) => [video.id, video]));
      await transcriptFetcher.fetchAll(targets.map((video) => video.id), {
        concurrency: transcriptSettings.concurrency,
        delayMs: transcriptSettings.requestDelayMs,
        signal,
        onEach: async (result) => {
          const video = byId.get(result.videoId);
          if (result.ok) {
            const fetchedAt = now().toISOString();
            const file = await depot.writeTranscript(result.videoId, {
              title: video?.title ?? '',
              url: video?.url ?? '',
              channel: video?.channel ?? '',
              publishedAt: video?.publishedAt ?? null,
              fetchedAt,
              transcriptLanguage: result.transcriptLanguage,
              wordCount: result.wordCount,
            }, result.text);
            await depot.updateVideo(result.videoId, {
              status: 'ok',
              transcriptLanguage: result.transcriptLanguage,
              fetchedAt,
              wordCount: result.wordCount,
              excerpt: result.excerpt,
              error: null,
              file,
            });
            done += 1;
          } else {
            await depot.updateVideo(result.videoId, {
              status: result.errorCode === 'no_transcript' ? 'no_transcript' : 'failed',
              error: result.errorCode,
            });
            failed += 1;
            note(`"${video?.title ?? result.videoId}" has no usable transcript (${result.errorCode}).`);
          }
          update({ progress: { total, done, failed } });
        },
      });
    }

    const videos = await depot.listVideos(courseId);
    const usable = videos.filter((video) => video.status === 'ok' && video.wordCount > 0);
    if (usable.length === 0) {
      throw new IngestError(
        'no_transcripts',
        'None of the videos have a usable transcript. The course may have captions disabled.',
      );
    }
    if (usable.length < videos.length) {
      note(`${videos.length - usable.length} video(s) had no usable transcript and were left out.`);
    }

    // 4. Topics.
    await depot.updateCourse(courseId, { status: 'clustering', stage: 'clustering' });
    update({ stage: 'clustering' });
    throwIfAborted(signal);

    const offered = [];
    for (const video of usable) {
      const text = await depot.readTranscript(video.id, { maxChars: transcriptSettings.maxChars ?? 200_000 });
      if (text && text.trim() !== '') {
        offered.push({ id: video.id, title: video.title, text });
      }
    }
    if (offered.length === 0) {
      throw new IngestError('no_transcripts', 'The stored transcripts could not be read back.');
    }

    const clustered = await cluster({
      courseTitle: discovery.courseTitle || course.title,
      videos: offered,
      apiKey: deepseek.apiKey ?? '',
      baseURL: deepseek.baseURL ?? '',
      model: deepseek.model,
      temperature: deepseek.temperature,
      maxTokens: deepseek.maxTokens,
      timeoutMs: deepseek.timeoutMs,
      topicsMin: llmSettings.topicsMin,
      topicsMax: llmSettings.topicsMax,
      clusterMaxCharsPerVideo: llmSettings.clusterMaxCharsPerVideo,
      clusterMaxTotalChars: llmSettings.clusterMaxTotalChars,
      warn: note,
    });
    addAll(warnings, clustered.warnings);
    if (clustered.error) note(clustered.error.message);

    const proposal = await depot.saveProposal(courseId, {
      source: clustered.source,
      model: clustered.model,
      error: clustered.error?.code ?? null,
      topics: clustered.topics,
    });

    await depot.updateCourse(courseId, {
      status: 'ready',
      stage: 'ready',
      error: null,
      warnings: warnings.slice(-50),
    });

    return {
      result: {
        courseId,
        jobId,
        videoCount: videos.length,
        transcriptCount: usable.length,
        failedCount: failed,
        topicCount: proposal?.topics?.length ?? 0,
        proposalId: proposal?.id ?? null,
        topicSource: clustered.source,
      },
    };
  } catch (err) {
    const message = err?.expose === false ? 'The ingest failed. Check the server log for details.' : err?.message;
    await depot.updateCourse(courseId, {
      status: 'failed',
      stage: null,
      error: typeof message === 'string' ? message.slice(0, 300) : 'The ingest failed.',
      warnings: warnings.slice(-50),
    }).catch(() => {});
    throw err;
  }
}
