test('fetchAll preserves input order, dedupes ids and bounds concurrency', async () => {
  let active = 0;
  let peak = 0;
  const seen = [];

  const { fetcher: transcript } = fetcher(async (videoId) => {
    active += 1;
    peak = Math.max(peak, active);
    await new Promise((resolve) => setTimeout(resolve, videoId === vid(1) ? 30 : 5));
    active -= 1;
    return segmentsOf(`Text ${videoId}`);
  }, { languages: ['en'], concurrency: 2 });

  const results = await transcript.fetchAll(
    [vid(1), vid(2), vid(1), 'bad', vid(3), vid(4)],
    { concurrency: 2, onEach: async (result) => { seen.push(result); } },
  );

  assert.deepEqual(results.map((result) => result.videoId), [vid(1), vid(2), vid(3), vid(4)]);
  assert.equal(seen.length, 4);
  assert.equal(peak, 2);
  assert.equal(results[0].text, `Text ${vid(1)}`);
});

test('fetchAll reports cancellation per video and still calls onEach', async () => {
  const { fetcher: transcript, calls } = fetcher(() => segmentsOf('Never'));
  const controller = new AbortController();
  controller.abort();
  const reported = [];

  const results = await transcript.fetchAll([vid(11), vid(12)], {
    signal: controller.signal,
    onEach: async (result) => { reported.push(result); },
  });

  assert.equal(results.length, 2);
  assert.deepEqual(reported.map((result) => result.errorCode), ['timeout', 'timeout']);
  assert.equal(calls.length, 0);
});
